def ai_chat_response(user_message):
    """Chat Agent, backed by real retrieval (TF-IDF over the Knowledge
    Center articles + any uploaded PDFs). If an Anthropic API key is set
    (Settings page, or ANTHROPIC_API_KEY env var), the retrieved chunks
    and bill data are sent to a real model call to generate the answer.
    Without a key, the answer is assembled directly from the retrieved
    text — still real retrieval, just no generative paraphrase step.
    Returns (text, sources, mode) where mode is 'llm' or 'retrieval'."""
    retrieved = rag_search(user_message, k=3)
    bill_facts = (
        f"Current month: {current_units} kWh, Rs. {current_bill:,}. "
        f"Previous month: {previous_units} kWh. Change: {pct_change:+.1f}%."
    )

    client = get_anthropic_client()
    if client is not None:
        context_block = "\n\n".join(f"Source: {r['title']}\n{r['text']}" for r in retrieved) \
            or "No matching knowledge base passages were retrieved for this question."
        try:
            resp = client.messages.create(
                model=st.session_state.get("llm_model", "claude-sonnet-5"),
                max_tokens=400,
                system=(
                    "You are PowerSense AI, an assistant inside a household electricity "
                    "dashboard. Answer the user's question using ONLY the bill data and "
                    "knowledge-base context provided below. Be concise (3-5 sentences). "
                    "If the context doesn't actually cover the question, say so plainly "
                    "instead of guessing or inventing numbers."
                ),
                messages=[{
                    "role": "user",
                    "content": f"Bill data:\n{bill_facts}\n\nKnowledge base context:\n{context_block}\n\nQuestion: {user_message}",
                }],
            )
            text = "".join(
                block.text for block in resp.content if getattr(block, "type", None) == "text"
            ).strip()
            if text:
                sources = [r["title"] for r in retrieved]
                return text, sources, "llm"
        except Exception as e:
            st.session_state["_last_llm_error"] = str(e)

    # Retrieval-only fallback (no key configured, or the API call failed)
    if retrieved:
        lead = retrieved[0]
        text = f"From **{lead['title']}**: {lead['text']}"
        if len(retrieved) > 1:
            text += f"\n\nAlso relevant — **{retrieved[1]['title']}**: {retrieved[1]['text']}"
        text += f"\n\n_Your numbers: {bill_facts}_"
        sources = [r["title"] for r in retrieved]
    else:
        text = (
            "I couldn't find anything in the Knowledge Center relevant to that. Try asking "
            "about tariff slabs, the FPA, billing cycles, sudden bill increases, AC energy "
            "saving, or how to read your meter — or add a PDF in the Knowledge Center page."
        )
        sources = []
    return text, sources, "retrieval"


