def _split_sentences(text):
    sentences = re.split(r"(?<=[.!?])\s+", text.strip())
    return [s.strip() for s in sentences if s.strip()]


def _chunk_text(text, sentences_per_chunk=3):
    """Groups sentences into small overlap-free chunks for indexing."""
    sents = _split_sentences(text)
    chunks = []
    for i in range(0, len(sents), sentences_per_chunk):
        chunk = " ".join(sents[i:i + sentences_per_chunk])
        if chunk:
            chunks.append(chunk)
    return chunks


def build_base_chunks():
    chunks = []
    for article in KNOWLEDGE_BASE:
        for c in _chunk_text(article["content"]):
            chunks.append({"title": article["title"], "category": article["category"], "text": c})
    return chunks


def extract_text_from_pdf(uploaded_file):
    """Real text extraction via pypdf. Returns '' (not an exception) for
    scanned/image-only PDFs or unreadable files, so callers can show an
    honest message instead of guessing."""
    if not PYPDF_AVAILABLE or uploaded_file is None:
        return ""
    try:
        reader = PdfReader(io.BytesIO(uploaded_file.getvalue()))
        return "\n".join(page.extract_text() or "" for page in reader.pages)
    except Exception:
        return ""


def get_rag_index():
    """Builds (and session-caches) a TF-IDF index over the built-in
    Knowledge Base articles plus any PDFs uploaded during this session.
    Rebuilds only when the set of custom chunks changes."""
    custom_chunks = st.session_state.get("custom_kb_chunks", [])
    version_key = f"base+{len(custom_chunks)}"

    cached = st.session_state.get("rag_index")
    if cached is not None and st.session_state.get("rag_index_version") == version_key:
        return cached

    chunks = build_base_chunks() + custom_chunks
    if not chunks or not SKLEARN_AVAILABLE:
        index = (None, None, chunks)
    else:
        texts = [c["text"] for c in chunks]
        vectorizer = TfidfVectorizer(stop_words="english", ngram_range=(1, 2))
        matrix = vectorizer.fit_transform(texts)
        index = (vectorizer, matrix, chunks)

    st.session_state.rag_index = index
    st.session_state.rag_index_version = version_key
    return index


def rag_search(query, k=3, min_score=0.06):
    """Real cosine-similarity retrieval over the TF-IDF index. Returns only
    chunks above min_score, so an off-topic question can legitimately
    return zero sources instead of always citing something."""
    vectorizer, matrix, chunks = get_rag_index()
    if vectorizer is None or matrix is None or not chunks:
        return []
    q_vec = vectorizer.transform([query])
    sims = cosine_similarity(q_vec, matrix).flatten()
    ranked = sims.argsort()[::-1][:k]
    results = []
    for i in ranked:
        if sims[i] >= min_score:
            item = dict(chunks[i])
            item["score"] = round(float(sims[i]), 3)
            results.append(item)
    return results


