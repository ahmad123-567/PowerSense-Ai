def parse_bill_text(text):
    """Best-effort regex extraction from raw bill text. Returns only the
    fields it can confidently find; anything not matched is left out so
    the caller can fall back to demo data for just that field."""
    patterns = {
        "consumer_id": r"(?:consumer\s*(?:id|no\.?|number)|reference\s*(?:no\.?|number))[:\s#-]*([A-Za-z0-9\-]{5,20})",
        "units_consumed": r"(?:units\s*consumed|total\s*units)[:\s]*([\d,]+)",
        "total_payable": r"(?:total\s*(?:payable|amount|bill)|amount\s*due)[:\s]*(?:rs\.?)?\s*([\d,]+)",
        "previous_reading": r"previous\s*reading[:\s]*([\d,]+)",
        "current_reading": r"current\s*reading[:\s]*([\d,]+)",
        "due_date": r"due\s*date[:\s]*([\d]{1,2}[-/\s][A-Za-z0-9]{2,10}[-/\s][\d]{2,4})",
    }
    found = {}
    for key, pat in patterns.items():
        m = re.search(pat, text, re.IGNORECASE)
        if m:
            found[key] = m.group(1).replace(",", "")
    return found


def ai_extract_bill(uploaded_file):
    """Bill Extraction Agent.
    For real PDF uploads: extracts text with pypdf and parses it with
    regex. Fields it finds are used as-is; fields it can't find fall back
    to the demo dataset, and the UI is told which case happened so it can
    say so honestly instead of silently pretending everything was parsed.
    """
    parsed = {}
    parse_status = "demo"

    if uploaded_file is not None:
        file_type = getattr(uploaded_file, "type", "") or ""
        if "pdf" in file_type:
            raw_text = extract_text_from_pdf(uploaded_file)
            if raw_text.strip():
                parsed = parse_bill_text(raw_text)
                parse_status = "parsed" if len(parsed) >= 3 else "partial"
            else:
                parse_status = "unreadable"
        else:
            parse_status = "image_no_ocr"

    base = {
        "consumer_id": "10-2938-4471",
        "billing_month": datetime.today().strftime("%B %Y"),
        "previous_reading": 18420,
        "current_reading": 18420 + current_units,
        "units_consumed": current_units,
        "electricity_charges": int(current_units * RATE_PER_UNIT),
        "taxes": int(current_units * RATE_PER_UNIT * 0.06),
        "fpa_adjustment": int(current_units * RATE_PER_UNIT * 0.02),
        "total_payable": current_bill,
        "due_date": (datetime.today() + timedelta(days=14)).strftime("%d %b %Y"),
    }

    for key in ["consumer_id", "previous_reading", "current_reading", "units_consumed", "total_payable", "due_date"]:
        if key in parsed:
            if key in ("consumer_id", "due_date"):
                base[key] = parsed[key]
            else:
                try:
                    base[key] = int(parsed[key])
                except ValueError:
                    pass

    if "units_consumed" in parsed:
        try:
            u = int(parsed["units_consumed"])
            base["electricity_charges"] = int(u * RATE_PER_UNIT)
            base["taxes"] = int(u * RATE_PER_UNIT * 0.06)
            base["fpa_adjustment"] = int(u * RATE_PER_UNIT * 0.02)
            if "total_payable" not in parsed:
                base["total_payable"] = int(u * RATE_PER_UNIT * 1.08)
        except ValueError:
            pass

    base["_parse_status"] = parse_status
    base["_fields_found"] = list(parsed.keys())
    return base


def compute_confidence(units_now, history_series):
    """Confidence for the bill-health/anomaly call, derived from a z-score
    of this month's units against the historical mean/std — not a fixed
    number. Returns (confidence_pct, z_score)."""
    hist = history_series.iloc[:-1] if len(history_series) > 1 else history_series
    mean_h = hist.mean()
    std_h = hist.std()
    if not std_h or np.isnan(std_h) or std_h == 0:
        return 60.0, 0.0
    z = abs(units_now - mean_h) / std_h
    confidence = round(min(99.0, 100 * (1 - np.exp(-z / 2))), 1)
    return confidence, round(float(z), 2)


def ai_bill_health(units_now, units_prev):
    """Bill Analysis Agent."""
    change = (units_now - units_prev) / units_prev * 100
    if change > 15:
        return "Needs Attention", "🔴", change
    elif change > 8:
        return "Watch", "🟡", change
    return "Normal", "🟢", change


def ai_why_bill_high(units_now, units_prev):
    """Consumption reasoning agent. The headline percentage is a real
    calculation; the contributing factors are whatever the RAG index
    actually retrieves for a 'why did my bill increase' query, so they
    change if you add or remove Knowledge Center content."""
    change = round((units_now - units_prev) / units_prev * 100, 1)
    retrieved = rag_search(
        "reasons electricity bill increased tariff slab peak hours FPA", k=3, min_score=0.02
    )
    if retrieved:
        contributors = [r["text"] for r in retrieved]
        contributor_sources = [r["title"] for r in retrieved]
    else:
        contributors = ["Higher total consumption this billing period drove the increase."]
        contributor_sources = []
    return change, contributors, contributor_sources


def ai_detect_anomaly(units_now, avg_units):
    """Problem Detection Agent. Severity is real math on real (if synthetic)
    numbers. Causes are pulled from the same RAG index used everywhere else
    in the app, instead of a second, separate hardcoded list that could
    silently drift from the Knowledge Center content."""
    diff_pct = round((units_now - avg_units) / avg_units * 100, 1)
    if diff_pct > 20:
        severity, badge = "High", "badge-red"
    elif diff_pct > 10:
        severity, badge = "Medium", "badge-orange"
    elif diff_pct > 3:
        severity, badge = "Low", "badge-yellow"
    else:
        severity, badge = "None", "badge-green"

    retrieved = rag_search(
        "possible causes unusual electricity consumption spike appliance", k=3, min_score=0.02
    )
    if retrieved:
        causes = [r["text"] for r in retrieved]
        cause_sources = [r["title"] for r in retrieved]
    else:
        causes = ["Not enough indexed knowledge to explain this — add a relevant article or PDF."]
        cause_sources = []
    return diff_pct, severity, badge, causes, cause_sources


